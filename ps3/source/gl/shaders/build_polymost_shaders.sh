#!/bin/sh
#
# Regenerates ../ps3gl_polymost_data.h: Polymost's GLSL shaders written in
# Cg for the RSX (polymost_vp.vcg, polymost_fp.fcg). NOT part of the normal
# build, the header is in the tree. Same tools as build_shaders.sh (cgc
# 3.1 and PSL1GHT's cgcomp -a); kept apart so the TyrQuakeCell programs,
# proven on hardware, are never rebuilt by accident.
#
#   cd ps3/source/gl/shaders && sh build_polymost_shaders.sh

set -e

CGC=${CGC:-cgc}
CGCOMP=${CGCOMP:-$PS3DEV/bin/cgcomp}

command -v "$CGC" >/dev/null 2>&1 || { echo "cgc not found (sudo apt install nvidia-cg-toolkit)"; exit 1; }
[ -x "$CGCOMP" ] || { echo "cgcomp not found at $CGCOMP"; exit 1; }

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

"$CGC" -quiet -profile vp40 -o "$TMP/polymost_vp.asm" polymost_vp.vcg
"$CGCOMP" -a -v "$TMP/polymost_vp.asm" "$TMP/polymost_vp.vpo" >/dev/null

"$CGC" -quiet -profile fp40 -o "$TMP/polymost_fp.asm" polymost_fp.fcg
"$CGCOMP" -a -f "$TMP/polymost_fp.asm" "$TMP/polymost_fp.fpo" >/dev/null

python3 - "$TMP" <<'PYEOF'
import sys
tmp = sys.argv[1]
out = ["/* ps3gl_polymost_data.h -- GENERATED by shaders/build_polymost_shaders.sh,",
       " * don't edit. Polymost's shaders for the RSX (cgc vp40/fp40 + PSL1GHT",
       " * cgcomp -a) from shaders/polymost_vp.vcg and polymost_fp.fcg. */",
       "",
       "#ifndef PS3GL_POLYMOST_DATA_H",
       "#define PS3GL_POLYMOST_DATA_H",
       ""]
def emit(name, path):
    data = open(path, "rb").read()
    out.append("static const unsigned char %s[] __attribute__((aligned(16))) = {" % name)
    for i in range(0, len(data), 12):
        out.append("\t" + ", ".join("0x%02x" % b for b in data[i:i+12]) + ",")
    out.append("};")
    out.append("")
emit("polymost_vp_vpo", tmp + "/polymost_vp.vpo")
emit("polymost_fp_fpo", tmp + "/polymost_fp.fpo")
out.append("#endif")
open("../ps3gl_polymost_data.h", "w").write("\n".join(out) + "\n")
print("wrote ../ps3gl_polymost_data.h")
PYEOF
